class TestAgentSpecMatrixExhaustiveness:
    """The matrix must be MECHANICALLY DERIVED from the closed enumerations, and
    every generated cell must be explicitly classified (neograph-00447)."""

    def test_pyagentspec_registry_is_complete(self) -> None:
        """The shared node-family registry must cover every concrete pyagentspec
        primitive -- a new one fails loud (step 1)."""
        assert_registry_complete()

    def test_modifier_combo_axis_is_a_loud_partition(self) -> None:
        """A new ModifierCombo member forces classification into supported vs
        unsupported (architect review M1) -- it cannot silently go uncovered."""
        assert SUPPORTED_COMBOS.isdisjoint(UNSUPPORTED_COMBOS)
        assert SUPPORTED_COMBOS | UNSUPPORTED_COMBOS == set(ModifierCombo), (
            "ModifierCombo has member(s) classified as neither SUPPORTED nor "
            f"UNSUPPORTED: {set(ModifierCombo) - SUPPORTED_COMBOS - UNSUPPORTED_COMBOS}. "
            "Classify every combo so the per-node cross product stays exhaustive."
        )

    def test_every_generated_cell_is_classified(self) -> None:
        """GREEN | RED_EXPORT | UNREPRESENTABLE must partition the generated set
        exactly -- a new mode/combo/config axis surfaces cells that force
        classification instead of silently under-covering (the sdfgz disease)."""
        assert GREEN.isdisjoint(UNREPRESENTABLE)
        union = GREEN | RED_EXPORT | UNREPRESENTABLE
        assert union == set(CELLS), (
            "generated cells not covered by an explicit bucket: "
            f"{set(CELLS) - union}; buckets over-reaching the generated set: "
            f"{union - set(CELLS)}"
        )

    def test_prior_green_cells_are_still_generated_and_green(self) -> None:
        """The 8 originally hand-typed cells must still be produced by the
        generator AND still classified GREEN (true coverage check, not a
        same-function tautology -- architect review M3)."""
        missing = _PRIOR_GREEN_CELL_IDS - set(CELLS)
        assert not missing, f"generator dropped prior cells: {sorted(missing)}"
        regressed = _PRIOR_GREEN_CELL_IDS - GREEN
        assert not regressed, f"prior GREEN cells no longer GREEN: {sorted(regressed)}"

    def test_oracle_axis_crosses_config_and_shape(self) -> None:
        """Oracle must be crossed with BOTH merge_fn/merge_prompt AND single/dict
        (the axis that let the merge_prompt cell escape -- architect review M3)."""
        for cfg in ORACLE_CONFIGS:
            for shape in SHAPES:
                assert f"scripted-oracle-{cfg}-{shape}" in CELLS


