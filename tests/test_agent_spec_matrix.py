class TestAgentSpecExportMatrix:
    """Every derived cell either exports to a valid Flow (GREEN), is a known
    export gap (RED_EXPORT -> xfail), or is unrepresentable in neograph."""

    @pytest.mark.parametrize("cell_id", sorted(CELLS))
    def test_export(self, cell_id: str, request: pytest.FixtureRequest) -> None:
        mode, combo, config, shape = CELLS[cell_id]

        if cell_id in UNREPRESENTABLE:
            # north-star: neograph rejects the construct at assembly time.
            with pytest.raises(ConstructError):
                build_cell(mode, combo, config, shape)
            return

        if cell_id in RED_EXPORT:
            request.node.add_marker(pytest.mark.xfail(reason=_I7K7J_BLOCKER, strict=True))

        construct = build_cell(mode, combo, config, shape)
        # Must not raise (hf505: Each + context input raised a pydantic
        # DataFlowEdge ValidationError here).
        flow = to_agent_spec(construct)
        assert flow is not None
        assert flow.nodes


class TestAgentSpecRoundTripMatrix:
    """Every GREEN cell must ROUND-TRIP: export then re-import into a valid
    Construct (from_agent_spec runs assembly validation, where 3lk2l's Each
    element-type mismatch was raised). RED_EXPORT cells fail at export already
    (xfail); UNREPRESENTABLE cells never build."""

    @pytest.mark.parametrize("cell_id", sorted(CELLS))
    def test_round_trip(self, cell_id: str, request: pytest.FixtureRequest) -> None:
        mode, combo, config, shape = CELLS[cell_id]

        if cell_id in UNREPRESENTABLE:
            with pytest.raises(ConstructError):
                build_cell(mode, combo, config, shape)
            return

        if cell_id in RED_EXPORT:
            request.node.add_marker(pytest.mark.xfail(reason=_I7K7J_BLOCKER, strict=True))

        construct = build_cell(mode, combo, config, shape)
        flow = to_agent_spec(construct)
        imported = from_agent_spec(flow)
        assert isinstance(imported, Construct)
        assert imported.nodes
